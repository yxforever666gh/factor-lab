def __getattr__(name: str):
    # ``long_only_portfolio`` imports the execution kernel through this package.
    # Loading monthly_research eagerly would loop back through the canonical
    # evaluator into long_only_portfolio.  Keep the public API while deferring
    # only this evaluator-dependent module until a caller asks for it.
    if name in _LAZY_MONTHLY_EXPORTS:
        from . import monthly_research

        value = getattr(monthly_research, name)
        globals()[name] = value
        return value
    raise AttributeError(name)
